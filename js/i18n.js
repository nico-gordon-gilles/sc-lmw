  function applyVars(s,vars){
    if(vars) Object.keys(vars).forEach(function(k){ s=s.split('{'+k+'}').join(vars[k]==null?'':vars[k]); });
    return s;
  }

  function canonLang(raw){
    if(raw==null) return null;
    var x=String(raw).trim();
    if(!x) return null;
    if(x==='de'||x==='en'||x==='zh-Hans'||x==='zh-Hant') return x;
    x=x.toLowerCase().replace(/_/g,'-');
    if(x==='auto') return null;
    if(x==='de'||x.indexOf('de-')===0) return 'de';
    if(x==='en'||x.indexOf('en-')===0) return 'en';
    if(x==='zh-hant'||x==='zh-tw'||x==='zh-hk'||x==='zh-mo'||x.indexOf('zh-hant')===0||x.indexOf('zh-tw')===0||x.indexOf('zh-hk')===0||x.indexOf('zh-mo')===0) return 'zh-Hant';
    if(x==='zh'||x==='zh-hans'||x==='zh-cn'||x==='zh-sg'||x.indexOf('zh-hans')===0||x.indexOf('zh-cn')===0||x.indexOf('zh-sg')===0||x.indexOf('zh-')===0) return 'zh-Hans';
    return null;
  }
  function browserLang(){
    var list=[];
    try{ if(navigator.languages&&navigator.languages.length) list=[].slice.call(navigator.languages); }catch(e){}
    if(navigator.language) list.push(navigator.language);
    else if(navigator.userLanguage) list.push(navigator.userLanguage);
    for(var i=0;i<list.length;i++){ var c=canonLang(list[i]); if(c) return c; }
    return 'en';
  }
